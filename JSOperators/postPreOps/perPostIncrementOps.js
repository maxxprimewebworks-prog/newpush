console.log('Pre Increment Operator');
var num = 10;
console.log('Initial value' + num);
///Pre-increment
console.log(++num);  ///num + 1 = 11
console.log(++num);  ///12
console.log(++num);  ///13


console.log('================');


console.log('Post Increment Operator');
var eat = 10;
console.log('Initial value' + eat);
///Post-increment
console.log(eat++);  ///eat + 0 = 10
console.log(eat++);  ///11
console.log(eat++);  ///12 